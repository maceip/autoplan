def test_simple_demo_task_spins_up_agent_and_lands_via_chief(tmp_path: Path, monkeypatch):
    # Create an isolated executable agy test binary that writes task_result.txt and emits real agy JSON.
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    agy_exec = bin_dir / "agy_test_cli"
    agy_exec.write_text(
        "#!/usr/bin/env python3\n"
        "import json, pathlib, sys\n"
        "if '--version' in sys.argv:\n"
        "    print('2.0.0-test')\n"
        "    sys.exit(0)\n"
        "pathlib.Path('task_result.txt').write_text('AUTOPLAN_DEMO_OK generated by antigravity\\n')\n"
        "print(json.dumps({'conversation_id': 'conv_test_123', 'status': 'SUCCESS', 'response': 'Created task_result.txt.'}))\n",
        encoding="utf-8",
    )
    agy_exec.chmod(agy_exec.stat().st_mode | stat.S_IEXEC)
    monkeypatch.setenv("AGY_BIN", str(agy_exec))

    client, store, chief, _ = make_client(tmp_path)
    resp = client.post("/api/agents/demo-task", json={"service": "antigravity"})
    assert resp.status_code == 201
    run_id = resp.get_json()["run"]["id"]

    # Wait for background worker thread to complete.
    deadline = time.time() + 10.0
    run = store.get_run(run_id)
    while run and run["state"] == "running" and time.time() < deadline:
        time.sleep(0.05)
        run = store.get_run(run_id)

    assert run is not None
    assert run["state"] == "succeeded"
    assert run["session_id"] == "conv_test_123"
    assert run["queue_item_id"]

    # Chief triages and runs the real git-grep test command on the demo repo branch.
    chief.process_once()
    item = store.get_item(run["queue_item_id"])
    assert item is not None
    assert item["status"] == "needs_review"
    assert item["result"]["test"]["passed"] is True

    # Operator approves -> Chief merges branch onto main and records merged_commit SHA.
    decide = client.post(
        f"/api/queue/items/{item['id']}/decision",
        json={"action": "approve", "note": "Verified demo task"},
    )
    assert decide.status_code == 200
    chief.process_once()

    landed = store.get_item(item["id"])
    assert landed is not None
    assert landed["status"] == "landed"
    assert landed["result"]["merged_commit"]
    merged_file = Path(landed["repo_path"]) / "task_result.txt"
    assert merged_file.is_file()
    assert "AUTOPLAN_DEMO_OK" in merged_file.read_text(encoding="utf-8")


def test_webclaw_sessions_history_and_send_lifecycle(tmp_path: Path, monkeypatch):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    mimo_exec = bin_dir / "mimo_test_cli"
    mimo_exec.write_text(
        "#!/usr/bin/env python3\n"
        "import json, sys\n"
        "if '--version' in sys.argv:\n"
        "    print('0.1.15')\n"
        "    sys.exit(0)\n"
        "print(json.dumps({'type': 'step_start', 'sessionID': 'ses_test_99'}))\n"
        "print(json.dumps({'type': 'text', 'sessionID': 'ses_test_99', 'part': {'type': 'text', 'text': 'Hello from Xiaomi MiMo'}}))\n"
        "print(json.dumps({'type': 'step_finish', 'sessionID': 'ses_test_99', 'part': {'tokens': {'total': 42}, 'cost': 0.001}}))\n",
        encoding="utf-8",
    )
    mimo_exec.chmod(mimo_exec.stat().st_mode | stat.S_IEXEC)
    monkeypatch.setenv("MIMO_BIN", str(mimo_exec))
    monkeypatch.setenv("MIMO_DEFAULT_MODEL", "xiaomi/mimo-v2.6-flash")

    client, store, _, _ = make_client(tmp_path)
    assert client.get("/api/webclaw/ping").get_json()["ok"] is True

    created = client.post(
        "/api/webclaw/sessions",
        json={"label": "MiMo Demo Chat", "service": "xiaomi-mimo"},
    ).get_json()
    assert created["ok"] is True
    friendly_id = created["friendlyId"]
    session_key = created["sessionKey"]

    patched = client.patch(
        "/api/webclaw/sessions",
        json={"friendlyId": friendly_id, "label": "MiMo Renamed"},
    ).get_json()
    assert patched["entry"]["label"] == "MiMo Renamed"

    sent = client.post(
        "/api/webclaw/send",
        json={"sessionKey": session_key, "service": "xiaomi-mimo", "message": "Say hi"},
    )
    assert sent.status_code == 200
    run_id = sent.get_json()["runId"]

    deadline = time.time() + 10.0
    run = store.get_run(run_id)
    while run and run["state"] == "running" and time.time() < deadline:
        time.sleep(0.05)
        run = store.get_run(run_id)

    assert run is not None and run["state"] == "succeeded"

    history = client.get(f"/api/webclaw/history?sessionKey={session_key}").get_json()
    assert len(history["messages"]) == 2
    assert history["messages"][0]["role"] == "user"
    assert history["messages"][1]["role"] == "assistant"
    assert "Hello from Xiaomi MiMo" in history["messages"][1]["content"][0]["text"]

    deleted = client.delete(f"/api/webclaw/sessions?sessionKey={session_key}")
    assert deleted.status_code == 200
    assert client.get(f"/api/webclaw/history?sessionKey={session_key}").status_code == 404
