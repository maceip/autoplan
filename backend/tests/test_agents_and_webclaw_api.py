"""Tests for Antigravity, MiniMax, and Xiaomi MiMo adapters, runs, ownership, and WebClaw API."""

from __future__ import annotations

import os
import stat
import subprocess
import time
from pathlib import Path

import pytest
from flask import Flask

from planaieditor.queue_api import setup_queue
from planaieditor.queue_store import QueueStore


def make_client(tmp_path: Path):
    app = Flask(__name__)
    store, chief = setup_queue(app, None, tmp_path, start_chief=False)
    return app.test_client(), store, chief, app.config["AGENT_MANAGER"]


def test_agents_list_reports_all_three_services(tmp_path: Path):
    client, _, _, _ = make_client(tmp_path)
    resp = client.get("/api/agents")
    assert resp.status_code == 200
    body = resp.get_json()
    assert body["success"] is True
    by_service = {svc["service"]: svc for svc in body["services"]}
    assert set(by_service.keys()) == {"antigravity", "minimax", "xiaomi-mimo"}
    for svc_id, info in by_service.items():
        assert info["mode"] in {"dispatch", "observe_only"}
        assert isinstance(info["observed_sessions_count"], int)
        assert isinstance(info["dispatch_ready"], bool)
        assert info["display_name"]


def test_scan_sessions_endpoints_and_unknown_service(tmp_path: Path):
    client, _, _, _ = make_client(tmp_path)
    for svc in ("antigravity", "minimax", "xiaomi-mimo"):
        resp = client.get(f"/api/agents/{svc}/sessions?limit=3")
        assert resp.status_code == 200
        payload = resp.get_json()
        assert payload["success"] is True
        assert payload["service"] == svc
        assert isinstance(payload["sessions"], list)

    missing = client.get("/api/agents/unknown-agent/sessions")
    assert missing.status_code == 404


def test_ownership_refuses_concurrent_active_claim(tmp_path: Path):
    store = QueueStore(tmp_path / "queue.db")
    run1 = store.create_run({"service": "antigravity", "prompt": "p1", "state": "running"})
    store.claim_ownership("/repo/a", "/repo/a", "main", "antigravity", run1["id"])

    with pytest.raises(ValueError, match="already claimed"):
        store.claim_ownership("/repo/a", "/repo/a", "main", "xiaomi-mimo", "run_other")

    store.release_ownership(run1["id"])
    claim2 = store.claim_ownership("/repo/a", "/repo/a", "main", "xiaomi-mimo", "run_other")
    assert claim2["service"] == "xiaomi-mimo"


